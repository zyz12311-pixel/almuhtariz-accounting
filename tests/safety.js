import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { openDb } from '../server/db.js';
import { seedCompany, setSetting, createInvoice, issueInvoice, getInvoice, createCreditNote } from '../server/core.js';
import { untlv } from '../server/lib.js';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'smartz-safety-'));
const db=openDb(path.join(dir,'safety.db'));
try {
seedCompany(db,'منشأة أصلية');
setSetting(db,'company',{name_ar:'منشأة أصلية',vat_number:'300000000000003',cr_number:'1234567890',street:'شارع الاختبار',building_number:'1234',district:'حي الاختبار',city:'الرياض',postal_code:'12345',country_code:'SA'});
const lines=[{description:'الأول',qty:2,unit_price:100},{description:'الثاني',qty:3,unit_price:50}];
const original=createInvoice(db,1,{lines});
assert.match(untlv(getInvoice(db,original).qr)[3],/\+03:00$/);
setSetting(db,'company',{name_ar:'اسم جديد',vat_number:'300000000000003',cr_number:'1234567890',street:'شارع الاختبار',building_number:'1234',district:'حي الاختبار',city:'الرياض',postal_code:'12345',country_code:'SA'});
assert.equal(getInvoice(db,original).company_snapshot.name_ar,'منشأة أصلية');
const note=createCreditNote(db,1,original,{lines:[{line_no:2,qty:1}],reason:'إرجاع'});
assert.equal(getInvoice(db,note).lines[0].line_no,2);
assert.equal(getInvoice(db,original).lines[1].remaining,2);
assert.throws(()=>createCreditNote(db,1,original,{lines:[],reason:'إرجاع'}));
assert.throws(()=>createCreditNote(db,1,original,{lines:[{line_no:2,qty:1},{line_no:2,qty:1}],reason:'إرجاع'}));
assert.throws(()=>createInvoice(db,1,{lines,payment:'credit'}));
assert.throws(()=>createInvoice(db,1,{lines:[{description:'غير صالح',qty:Infinity,unit_price:1}]}));
const draft=createInvoice(db,1,{lines,draft:true});
const before=db.prepare('SELECT * FROM chain WHERE branch_id=1').get();
db.exec("CREATE TRIGGER fail_journal BEFORE INSERT ON journal_entries BEGIN SELECT RAISE(ABORT,'forced failure'); END;");
assert.throws(()=>issueInvoice(db,draft),/forced failure/);
assert.equal(getInvoice(db,draft).status,'draft');
assert.deepEqual(db.prepare('SELECT * FROM chain WHERE branch_id=1').get(),before);
assert.equal(db.prepare('SELECT COUNT(*) n FROM invoice_snapshots WHERE invoice_id=?').get(draft).n,0);
db.exec('DROP TRIGGER fail_journal');
issueInvoice(db,draft);
assert.equal(getInvoice(db,draft).status,'issued');
assert.throws(()=>issueInvoice(db,draft));
assert.equal(db.prepare('SELECT COUNT(*) n FROM sync_outbox').get().n,3);
assert.equal(db.prepare('SELECT COUNT(*) n FROM installation').get().n,1);
assert.throws(()=>db.exec("UPDATE sync_outbox SET event_type='changed'"));
console.log('نجحت اختبارات سلامة الإصدار وحفظ التاريخ والإرجاع والتراجع عند الفشل');
} finally { db.close(); }
