-- No browser can assign itself an owner role or write posted ledgers directly.
create schema if not exists private;
revoke all on schema private from public,anon;
grant usage on schema private to authenticated;
create function private.has_org_role(p_org uuid,p_roles text[]) returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.organization_members m where m.organization_id=p_org and m.user_id=(select auth.uid()) and m.active and m.role=any(p_roles));
$$;
revoke all on function private.has_org_role(uuid,text[]) from public,anon;
grant execute on function private.has_org_role(uuid,text[]) to authenticated;
create function private.assigned_pos(p_org uuid,p_pos uuid default null) returns boolean language sql stable security definer set search_path='' as $$
 select private.has_org_role(p_org,array['staff']) and exists(select 1 from public.pos_user_access a join public.pos_points p on p.organization_id=a.organization_id and p.id=a.pos_id where a.organization_id=p_org and a.user_id=(select auth.uid()) and p.active and (p_pos is null or p.id=p_pos));
$$;
revoke all on function private.assigned_pos(uuid,uuid) from public,anon;
grant execute on function private.assigned_pos(uuid,uuid) to authenticated;
